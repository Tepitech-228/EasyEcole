CREATE TABLE IF NOT EXISTS `ged_fichiers_stockes` (
  `id` INT UNSIGNED NOT NULL AUTO_INCREMENT,
  `originKey` VARCHAR(500) NOT NULL,
  `originType` ENUM('import', 'legacy') NOT NULL,
  `sourceTable` VARCHAR(100) NULL,
  `sourceRecordId` VARCHAR(191) NULL,
  `sourceColumn` VARCHAR(100) NULL,
  `titre` VARCHAR(255) NOT NULL,
  `nomFichier` VARCHAR(255) NOT NULL,
  `relativePath` VARCHAR(1000) NOT NULL,
  `mimeType` VARCHAR(120) NOT NULL,
  `taille` BIGINT UNSIGNED NOT NULL DEFAULT 0,
  `integrityHash` CHAR(64) NULL,
  `categorie` ENUM('academique', 'financier', 'administratif', 'autre') NOT NULL DEFAULT 'autre',
  `anneeAcademiqueId` INT UNSIGNED NULL,
  `etablissementId` INT UNSIGNED NULL,
  `filiereId` INT UNSIGNED NULL,
  `filiere` VARCHAR(191) NULL,
  `niveauEtudeId` INT UNSIGNED NULL,
  `parcoursId` INT UNSIGNED NULL,
  `classeId` INT UNSIGNED NULL,
  `createdBy` INT UNSIGNED NULL,
  `createdAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updatedAt` DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uq_ged_fichiers_stockes_origin` (`originKey`),
  KEY `idx_ged_fichiers_stockes_site_categorie` (`etablissementId`, `categorie`),
  KEY `idx_ged_fichiers_stockes_annee` (`anneeAcademiqueId`),
  KEY `idx_ged_fichiers_stockes_parcours` (`parcoursId`),
  KEY `idx_ged_fichiers_stockes_classe` (`classeId`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
