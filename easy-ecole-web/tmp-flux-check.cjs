const dotenv = require('D:/EasyEcole/easy-ecole-backend/node_modules/dotenv')
dotenv.config({ path: 'D:/EasyEcole/easy-ecole-backend/.env' })
const { Sequelize } = require('D:/EasyEcole/easy-ecole-backend/node_modules/sequelize')
const s = new Sequelize(process.env.DB_NAME, process.env.DB_USER, process.env.DB_PASSWORD, { host: process.env.DB_HOST, dialect: 'mysql', logging: false })

;(async () => {
    const [tables] = await s.query('SHOW TABLES')
    console.log('TABLES:', tables.map(r => Object.values(r)[0]).join(', '))
    console.log('')
    // Utilisateurs (chercher toutes les tables avec 'user' ou 'utilisateur' dans le nom)
    const [likeTables] = await s.query("SHOW TABLES LIKE '%utilisateur%'")
    console.log('tables utilisateur:', likeTables.map(r => Object.values(r)[0]).join(', '))
    const [likeUsers] = await s.query("SHOW TABLES LIKE '%user%'")
    console.log('tables user:', likeUsers.map(r => Object.values(r)[0]).join(', '))
    await s.close()
})().catch(e => { console.error('ERR', e.message); process.exit(1) })
